export function formatCommandHelp(id, lang) {
  const meta = COMMANDS[id];
  if (!meta) return "";
  const usage = meta.usage[lang] || meta.usage.pt;
  const desc = meta.desc[lang] || meta.desc.pt;
  const emoji = CMD_EMOJI[id] || "›";
  return `│ ${emoji} *${usage}*\n│ ${desc}`;
}
